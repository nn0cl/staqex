"""Explicit context contracts for extracted evaluator services."""

from __future__ import annotations

from typing import Any, Mapping, MutableMapping, Protocol, TextIO

from ...ast_nodes import CompilationUnit


class EvaluatorContext(Protocol):
    """The single live state owner exposed to evaluation services.

    The protocol describes orchestration callbacks rather than copying the
    evaluator's mutable maps. Concrete state remains owned by ``Evaluator``.
    """

    def _stateful_evolution_context(self) -> Any: ...

    def _bind_names(
        self, joint: Any, names: list[str], expr: Any, *,
        logs: list[str] | None = None, inspect_out: Any = None
    ) -> Any: ...
    def _bind(
        self, joint: Any, name: str, expr: Any, *,
        logs: list[str] | None = None, inspect_out: Any = None
    ) -> Any: ...

    def _operator_environment(self) -> Mapping[str, Any]: ...
    def _grid_hamiltonian_environment(self) -> Mapping[str, Any]: ...
    def _function_environment(self) -> Mapping[str, Any]: ...
    def _object_environment(self) -> MutableMapping[str, Any]: ...
    def _class_environment(self) -> Mapping[str, Any]: ...
    def _struct_environment(self) -> Mapping[str, Any]: ...
    def _enum_environment(self) -> Mapping[str, Any]: ...
    def _second_quantized_environment(self) -> Mapping[str, Any]: ...
    def _operator_array_context(self) -> Mapping[str, Any]: ...
    def _evaluate_value_with_unit(self, expr: Any, assign: dict[str, Any]) -> Any: ...
    def _evaluate_unit_convert(self, expr: Any, assign: dict[str, Any]) -> Any: ...
    def _evaluate_classical_value(
        self, expr: Any, assign: dict[str, Any]
    ) -> Any: ...
    def _evaluate_nested_value(self, expr: Any, assign: dict[str, Any]) -> Any: ...
    def _value_environment(self) -> Mapping[str, Any]: ...
    def _continuous_field_port(self) -> Any: ...
    def _runtime_seed(self) -> int | None: ...
    def _store_runtime_object(self, name: str, value: Any) -> None: ...
    def _evaluate_set_comprehension(self, expr: Any, assign: dict[str, Any]) -> Any: ...
    def _resolve_receiver_instance(self, expr: Any) -> Any: ...
    def _frame_environment(self) -> Mapping[str, Any]: ...
    def _restore_frame(self, receiver: Any, frame_units: dict[str, str]) -> None: ...
    def _expr_qualname(self, expr: Any) -> str | None: ...
    def _construct_instance(self, class_name: str, expr: Any) -> Any: ...
    def _construct_struct(self, struct_name: str, expr: Any) -> Any: ...
    def _construct_instance_body(self, class_name: str, expr: Any) -> Any: ...
    def _construct_struct_body(
        self, struct_name: str, expr: Any, assign: dict[str, Any] | None = None
    ) -> Any: ...
    def _run_init_body(self, receiver: Any, init: Any, args: list[Any]) -> None: ...
    def _execute_assignment_body(
        self, stmt: Any, local: dict[str, Any] | None = None
    ) -> None: ...
    def _make_class_instance(
        self, class_name: str, fields: dict[str, Any], mutable: set[str]
    ) -> Any: ...
    def _make_struct_value(
        self, struct_name: str, fields: dict[str, Any], field_units: dict[str, str]
    ) -> Any: ...
    def _copy_runtime_value(self, value: Any) -> Any: ...
    def _set_initializing(self, value: bool) -> None: ...
    def _is_initializing(self) -> bool: ...
    def _set_frame_units(self, value: dict[str, str]) -> None: ...
    def _scalar_units_environment(self) -> MutableMapping[str, str]: ...
    def _fill_partial(self, partial: Any, args: list[Any]) -> Any: ...
    def _bind_user_fun(
        self, joint: Any, names: list[str], expr: Any, fun: Any
    ) -> Any: ...
    def _bind_user_function_body(
        self,
        joint: Any,
        names: list[str],
        expr: Any,
        fun: Any,
        *,
        logs: list[str] | None = None,
        inspect_out: Any = None,
    ) -> Any: ...
    def _bind_method(
        self,
        joint: Any,
        name: str,
        receiver: Any,
        method: Any,
        args: list[Any],
    ) -> Any: ...
    def _bind_method_body(
        self,
        joint: Any,
        name: str,
        receiver: Any,
        method: Any,
        args: list[Any],
        *,
        logs: list[str] | None = None,
        inspect_out: Any = None,
    ) -> Any: ...
    def _operator_name(self, expr: Any) -> str: ...
    def _lit(self, expr: Any) -> Any: ...
    def _as_unary_fn(self, expr: Any) -> Any: ...
    def _project_onto_operator(
        self, joint: Any, source: str, operator: str
    ) -> Any: ...
    def _bind_finiteize(self, joint: Any, name: str, expr: Any) -> Any: ...
    def _bind_finiteize_continuous(self, joint: Any, name: str, expr: Any) -> Any: ...
    def _bind_field_from_host(self, joint: Any, name: str, expr: Any) -> Any: ...
    def _bind_continuous_compose(
        self,
        joint: Any,
        name: str,
        expr: Any,
        *,
        op_name: str,
        arity: tuple[int, ...],
    ) -> Any: ...
    def _bind_prepare_selection(self, joint: Any, name: str, expr: Any) -> Any: ...
    def _bind_inner(self, joint: Any, name: str, expr: Any) -> Any: ...
    def _execute_assignment(self, stmt: Any) -> None: ...
    def _require_uncompute_zero(self, joint: Any, name: str) -> None: ...
    def _eval_struct_arg(
        self, arg: Any, assign: dict[str, Any] | None = None
    ) -> tuple[Any, str | None]: ...
    def _is_closed(self, expr: Any) -> bool: ...
    def _current_receiver(self) -> Any: ...
    def _set_current_receiver(self, value: Any) -> None: ...
    def _make_partial_value(self, fun_name: str, slots: list[Any]) -> Any: ...
    def _compilation_unit(self) -> Any: ...

    def _joint_coord_names(self, joint: Any) -> set[str]: ...
    def _trace_out_dead_fn_locals(
        self, joint: Any, pre_live: set[str], result_names: list[str]
    ) -> Any: ...
    def _set_fusion_evidence(
        self,
        algebraic: tuple[float, float] | None,
        polynomial: tuple[float, ...] | None,
    ) -> None: ...

    def _prepare_execution_state(self, unit: CompilationUnit) -> None: ...
    def _execute_main_statement(self, statement: Any, state: Any) -> Any: ...

    _eval_result_type: Any
    _enum_value_type: Any

    def _unitary_operator_definition(self, name: str) -> Any | None: ...

    def _unitary_operator_environment(self) -> Mapping[str, Any]: ...

    def _scalar_environment(self) -> MutableMapping[str, Any]: ...
    def _put_unit(
        self, store: MutableMapping[str, str], name: str, unit: str | None
    ) -> None: ...
    def _unit_for(self, name: str) -> str | None: ...
    def _scalar_unit(self, name: str) -> str | None: ...
    def _make_enum_value(self, enum_name: str, variant: str) -> Any: ...
    def _evaluate_classical_call(self, expr: Any, assign: dict[str, Any]) -> Any: ...
    def _evaluate_classical_op_binder(self, expr: Any, assign: dict[str, Any]) -> Any: ...

    def _verify_static_uncompute_bind(
        self, joint: Any, name: str, expr: Any
    ) -> None: ...
    def _bind_evolve(self, joint: Any, names: list[str], expr: Any) -> Any: ...
    def _bind_tensor(self, joint: Any, names: list[str], expr: Any) -> Any: ...
    def _bind_apply_multi(self, joint: Any, names: list[str], expr: Any) -> Any: ...
    def _bind_cnot_multi(self, joint: Any, names: list[str], expr: Any) -> Any: ...
    def _bind_ket(self, joint: Any, name: str, expr: Any) -> Any: ...
    def _bind_ket_sum_binder(self, joint: Any, name: str, expr: Any) -> Any: ...
    def _compute_norm(self, joint: Any, expr: Any) -> float: ...
    def _is_state_producing_bind_expr(self, expr: Any) -> bool: ...
    def _bind_scaled_state(
        self, joint: Any, name: str, state_expr: Any, scalar_expr: Any
    ) -> Any: ...
    def _bind_state_divided_by_norm(
        self, joint: Any, name: str, state_expr: Any, norm_expr: Any
    ) -> Any: ...
    def _resolve_scientific_binding(self, name: str, available: Any) -> str: ...
    def _materialize_outer(self, joint: Any, expr: Any) -> Any: ...
    def _bind_when(self, joint: Any, name: str, expr: Any) -> Any: ...
    def _expr_marginal(self, joint: Any, expr: Any) -> Any: ...
    def _lit(self, expr: Any) -> Any: ...
    def _try_bind_fused_unary_pipe(
        self, joint: Any, name: str, expr: Any, *, logs: Any = None, inspect_out: Any = None
    ) -> Any: ...
    def _piped_call(self, expr: Any) -> Any: ...
    def _bind_block_expr(self, joint: Any, name: str, expr: Any) -> Any: ...

    def _static_register_size(self, name: str) -> int | None: ...

    def _require_runtime_plan_family(
        self, plan: Any, family: str, payload_name: str
    ) -> None: ...

    def _execute_deferred_state_measure_plan(
        self, unit: CompilationUnit, *, stdout: TextIO | None = None
    ) -> Any: ...

    def _main_deferred_eligible(self, statements: list[Any]) -> bool: ...

    def _is_minimal_local_evolution(self, unit: CompilationUnit) -> bool: ...

    def _evolution_runtime_unit(self, unit: CompilationUnit) -> CompilationUnit: ...

    def _binder_runtime_unit(self, unit: CompilationUnit) -> CompilationUnit: ...

    def _is_deferred_callable_eligible(self, unit: CompilationUnit) -> bool: ...

    def _is_first_runtime_family(self, unit: CompilationUnit, plan: Any) -> bool: ...

    def _execute_first_runtime_family(
        self, unit: CompilationUnit, *, stdout: TextIO | None = None
    ) -> Any: ...

    def _run_legacy_ast_body(
        self, unit: CompilationUnit, *, stdout: TextIO | None = None
    ) -> Any: ...

    def _evaluate_value(self, expr: Any, assign: dict[str, Any]) -> Any: ...

    def _resolve_operator(
        self,
        expr: Any,
        *,
        objects: dict[str, Any] | None = None,
        extra_arrays: dict[str, Any] | None = None,
    ) -> Any: ...

    def _execute_evolution(
        self, joint: Any, names: list[str], expr: Any
    ) -> Any: ...

    def _bind_call(self, joint: Any, name: str, expr: Any) -> Any: ...


    def _legacy_resolve_operator(self, expr: Any) -> Any: ...

    def _legacy_hamiltonian_evolve_one_step(
        self, joint: Any, names: list[str], expr: Any
    ) -> Any: ...
